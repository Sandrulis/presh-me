import type { Portfolio } from "@/app/lib/types";
import { registerThemes, type Theme } from "@/app/lib/themes";

export type DemoProfile = {
  role: string;
  page: Portfolio;
  theme: Theme;
};

type DemoPageExtras = Pick<
  Portfolio,
  "headerLayout" | "bannerColor" | "bannerHeight" | "bannerFade" | "pageColor"
>;

const stamp = "2026-01-01T00:00:00.000Z";

function demo(
  handle: string,
  role: string,
  displayName: string,
  bio: string,
  theme: Theme,
  socials: Portfolio["socials"],
  blocks: Portfolio["blocks"],
  avatarUrl: string | null = null,
  extras: DemoPageExtras = {},
): DemoProfile {
  return {
    role,
    theme,
    page: {
      id: `demo-${handle}`,
      accountId: "example",
      handle,
      displayName,
      bio,
      avatarUrl,
      themeId: theme.id,
      published: true,
      socials,
      blocks,
      createdAt: stamp,
      updatedAt: stamp,
      ...extras,
    },
  };
}

